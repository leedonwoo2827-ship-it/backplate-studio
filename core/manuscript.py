# -*- coding: utf-8 -*-
"""원고 JSON 의 자기 설명.

★ **규격은 한 곳에만 둔다 — 내보내는 파일 맨 위.**

이 파일을 받는 쪽은 대개 이 레포를 안 가지고 있다(다른 에이전트, 다른 PC,
메신저로 건네받은 사람). 별도 문서에 규격을 적어 두면 파일만 받은 쪽은 그것을
못 읽고, 두 벌이 되면 반드시 어긋난다. 그래서 파일이 스스로 설명하게 한다.

`_` 로 시작하는 키는 불러올 때 무시된다 — 설명이 데이터로 새어 들어가지 않는다.
"""
from __future__ import annotations

from typing import Any, Dict

# 슬라이드가 가질 수 있는 미디어 종류. **이 다섯뿐이다.**
#
# ★ 이 목록이 **유일한 출처**다. 예전엔 server.py 두 곳과 여기에 같은 튜플이
#   따로 적혀 있었는데, 종류를 하나 늘리면 세 곳을 다 고쳐야 했다. 한 곳이라도
#   빠지면 그 종류가 **조용히 "text" 로 깎여** 사라진다 — 목차를 한 번 저장하는
#   것만으로 html 장이 전부 글자 장이 되는 사고가 난다. 그래서 여기서 가져다 쓴다.
#
#   html — 참고 원고(HTML)의 한 항목을 **글 그대로** 얹은 장. 그림이 아니라서
#          줄 하나씩 시간에 맞춰 나타나게 할 수 있다(s2c 가 만든다).
#   thumb — 표지·마무리처럼 **그림 한 장이 화면을 통째로 덮는** 장.
#           `text_image` 와 재료는 같지만(번호로 들어오는 그림 한 장) 화면을
#           쓰는 방식이 다르다 — 상자에 앉히지 않고 꽉 채운다.
#           ★ `text_image` 를 고쳐 쓰지 않고 **따로 둔다.** 그 유형은 글 옆에
#             그림이 붙는 옛 레인이라 지우면 다른 데가 깨진다(2026-08-17).
MEDIA_KINDS = ("text", "text_image", "thumb", "html", "video", "code")

# ★ 주석 한 뭉치다. 설명서가 아니다 — 데이터를 보러 연 사람 앞을 가리면 안 된다.
#   남기는 것은 **그 자리에서만 알 수 있는 것**뿐이다: 고를 수 있는 값과, 비우면
#   어떻게 되는지. 문체·길이·금지 같은 것은 만드는 쪽에 말로 시킬 내용이다.
SPEC: Dict[str, Any] = {
    "규칙": "title 필수 · 모르는 칸은 \"\" · no 는 무시(순서대로 1부터 다시 매김) "
            "· _ 로 시작하는 키는 무시",
    "media_kind": list(MEDIA_KINDS),
    "kind": ["cover", "context", "feature", "architecture", "decision",
             "metric", "ops", "note", "closing"],
    "tone": ["pitch", "bullet", "explain"],
    "section": "sections[].id 중 하나. 없는 이름이면 새로 생김",
    "narration.text": "TTS 발음 교정본. 비우면 srt_text 를 그대로 읽음 (ODA→오디에이)",
}


def wrap(doc: Dict[str, Any]) -> Dict[str, Any]:
    """주석을 맨 위에 얹는다. 내보내는 모든 곳에서 같다 — 목차·초안·완성본.

    파일이 어디로 가든 규격이 같이 간다. 그게 이 주석을 파일 안에 둔 이유다.
    """
    return {"_읽는법": SPEC, **doc}
